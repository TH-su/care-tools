say('\n【9】辞書の健全性（同じ薬剤名が2つの分類に入っていないか）');
{
  /* 実装は「先に定義した分類が勝つ」。意図しない重複は取り違えの元なので数える。
     重複が出たら、どちらの分類が正しいかを薬剤師が決めて片方を消す。 */
  const src = fs.readFileSync(path.join(THEME, 'meds-effect-dict.js'), 'utf8');
  const body = src.slice(src.indexOf('var BY_LABEL'), src.indexOf('/* ── 照合の下ごしらえ ── */'));
  const seen = {}, dup = [];
  const re = /'([^']+)':\s*\[([\s\S]*?)\]/g;
  let m;
  while ((m = re.exec(body)) !== null) {
    const label = m[1];
    (m[2].match(/'[^']+'/g) || []).forEach(function (q) {
      const name = q.slice(1, -1);
      if (seen[name] && seen[name] !== label) dup.push(name + '（' + seen[name] + ' と ' + label + '）');
      else seen[name] = label;
    });
  }
  t('分類をまたぐ重複が無い', dup.length === 0, dup.slice(0, 10));
  t('収録名が300件以上', Object.keys(seen).length >= 300, Object.keys(seen).length);
}

