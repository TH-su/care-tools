  /* 全角英数を半角へ・英字を小文字へ・空白と中黒を落とす。
     薬剤名の表記ゆれ（Ａ→A、フェロ・グラデュメット→フェログラデュメット）を吸収するため。
     ★カタカナ・漢字はそのまま（濁点や長音を触ると別の薬に化ける） */
  function norm(s) {
    return String(s == null ? '' : s)
      .replace(/[Ａ-Ｚａ-ｚ０-９]/g, function (c) {
        return String.fromCharCode(c.charCodeAt(0) - 0xFEE0);
      })
      .toLowerCase()
      .replace(/[\s　・･]/g, '');
  }

  var ENTRIES = null;   // [{key, label}] を長い順に並べたもの

  function build() {
    if (ENTRIES) return ENTRIES;
    var list = [], seen = {};
    for (var label in BY_LABEL) {
      if (!Object.prototype.hasOwnProperty.call(BY_LABEL, label)) continue;
      var names = BY_LABEL[label];
      for (var i = 0; i < names.length; i++) {
        var k = norm(names[i]);
        if (k.length < 2) continue;             // 短すぎる語は誤爆するので採らない
        if (seen[k]) continue;                  // 先に定義した分類を優先（同名は1つだけ）
        seen[k] = 1;
        list.push({ key: k, label: label });
      }
    }
    /* ★長い語から順に照合する。「アムロジピン」より先に「アムロジピンOD」を試したい、
       「テオドール」を「テオ」で拾わない、といった取り違えを防ぐ。 */
    list.sort(function (a, b) { return b.key.length - a.key.length; });
    ENTRIES = list;
    return ENTRIES;
  }

  /* 1行（薬剤名＋用量＋用法）から分類を1つ返す。引けなければ空文字。 */
  function effectOf(line) {
    var s = norm(line);
    if (!s) return '';
    var list = build();
    for (var i = 0; i < list.length; i++) {
      if (s.indexOf(list[i].key) >= 0) return list[i].label;
    }
    return '';
  }

  /* 複数行をまとめて。行数は必ず入力と同じ（行を捨てない・増やさない）。 */
  function effectsFor(text) {
    var lines = String(text == null ? '' : text).replace(/\r\n/g, '\n').split('\n');
    var out = [];
    for (var i = 0; i < lines.length; i++) out.push(effectOf(lines[i]));
    return out;
  }

